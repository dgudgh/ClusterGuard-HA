package scripts

import (
	"os"
	"os/exec"
	"path/filepath"
	"strings"
	"testing"
)

func TestInstallerKnownHostsCoversCorrectedAddressesWithoutReplacingPins(t *testing.T) {
	script, err := os.ReadFile("install_clusterguard.sh")
	if err != nil {
		t.Fatal(err)
	}
	function, ok := extractShellFunction(string(script), "prepare_known_hosts")
	if !ok {
		t.Fatal("missing prepare_known_hosts")
	}
	for _, tc := range []struct {
		name, port, scan string
		accept, explicit bool
		covered, pass    bool
		fresh            bool
	}{
		{name: "corrected-ip", port: "22", accept: true, pass: true},
		{name: "nonstandard-port", port: "2222", accept: true, pass: true},
		{name: "refuse-new-pin-without-accept", port: "22"},
		{name: "scan-fails-preserve-cache", port: "22", accept: true, scan: "fail"},
		{name: "empty-scan-preserve-cache", port: "22", accept: true, scan: "empty"},
		{name: "explicit-file-read-only", port: "22", accept: true, explicit: true},
		{name: "explicit-covered", port: "22", explicit: true, covered: true, pass: true},
		{name: "existing-pin-never-rescanned", port: "22", accept: true, covered: true, pass: true},
		{name: "first-use-empty-cache", port: "22", accept: true, fresh: true, pass: true},
		{name: "partial-scan-fails-preserve-cache", port: "22", accept: true, scan: "second-fail"},
		{name: "scan-wrong-address", port: "22", accept: true, scan: "wrong-host"},
	} {
		t.Run(tc.name, func(t *testing.T) {
			root := t.TempDir()
			key := filepath.Join(root, "key")
			if out, err := exec.Command("ssh-keygen", "-q", "-t", "ed25519", "-N", "", "-f", key).CombinedOutput(); err != nil {
				t.Fatalf("test key: %v: %s", err, out)
			}
			pub, _ := os.ReadFile(key + ".pub")
			fields := strings.Fields(string(pub))
			public := fields[0] + " " + fields[1]
			known := filepath.Join(root, "ssh", "installer_known_hosts")
			selector := "10.9.30.115"
			if tc.port != "22" {
				selector = "[10.9.30.115]:" + tc.port
			}
			initial := "10.9.30.118 " + public + "\n"
			if tc.covered {
				initial += selector + " " + public + "\n"
			}
			if !tc.fresh {
				writeFile(t, known, initial, 0600)
				// Test lookups of hashed caches, as generated by the installer.
				if out, err := exec.Command("ssh-keygen", "-H", "-f", known).CombinedOutput(); err != nil {
					t.Fatalf("hash fixture: %v: %s", err, out)
				}
			}
			before, _ := os.ReadFile(known)
			input := ""
			if tc.explicit {
				input = known
			}
			program := `set -euo pipefail
known_hosts_input="$TEST_INPUT"
work_dir="$TEST_ROOT"
ssh_port="$TEST_PORT"
accept_host_keys="$TEST_ACCEPT"
new_known_hosts=false
all_nodes=(10.9.30.115)
[[ "$TEST_SCAN" != second-fail ]] || all_nodes+=(10.9.30.116)
log() { :; }
die() { printf '%s\n' "$*" >&2; exit 90; }
ssh-keyscan() {
 target="${!#}"
 printf 'scan\n' >> "$TEST_ROOT/scanned"
 [[ "$TEST_SCAN" != fail ]] || return 1
 [[ "$TEST_SCAN" != empty ]] || return 0
 [[ "$TEST_SCAN" != second-fail || "$target" != 10.9.30.116 ]] || return 1
 [[ "$TEST_SCAN" != wrong-host ]] || { printf '10.9.30.117 %s\n' "$TEST_PUBLIC_KEY"; return 0; }
 printf '%s %s\n' "$TEST_SELECTOR" "$TEST_PUBLIC_KEY"
}
` + function + "\nprepare_known_hosts\n"
			cmd := exec.Command("bash", "-c", program)
			accept := "false"
			if tc.accept {
				accept = "true"
			}
			cmd.Env = append(os.Environ(), "TEST_ROOT="+root, "TEST_INPUT="+input, "TEST_PORT="+tc.port, "TEST_ACCEPT="+accept, "TEST_SCAN="+tc.scan, "TEST_SELECTOR="+selector, "TEST_PUBLIC_KEY="+public)
			out, runErr := cmd.CombinedOutput()
			if (runErr == nil) != tc.pass {
				t.Fatalf("pass=%v want=%v: %v: %s", runErr == nil, tc.pass, runErr, out)
			}
			after, _ := os.ReadFile(known)
			if !strings.HasPrefix(string(after), string(before)) {
				t.Fatalf("existing pins replaced: before=%s after=%s", before, after)
			}
			if !tc.pass || tc.explicit || tc.covered {
				if string(after) != string(before) {
					t.Fatalf("cache changed without an authorized new pin: %s", after)
				}
			}
			if tc.pass {
				if out, err := exec.Command("ssh-keygen", "-F", selector, "-f", known).CombinedOutput(); err != nil {
					t.Fatalf("success left target untrusted: %v: %s", err, out)
				}
			}
			if tc.explicit || tc.covered || !tc.accept {
				if _, err := os.Stat(filepath.Join(root, "scanned")); !os.IsNotExist(err) {
					t.Fatal("rescanned pinned address or explicit/no-accept file")
				}
			}
			for _, pattern := range []string{known + ".pending.*", known + ".scan.*"} {
				matches, _ := filepath.Glob(pattern)
				if len(matches) != 0 {
					t.Fatalf("left partial trust material after completion: %v", matches)
				}
			}
		})
	}
}
