#!/usr/bin/env node
"use strict";

// Renders the bilingual hotfix catalogue from the signed patches that actually
// exist on disk. The catalogue is generated, never hand-written: a hand-kept
// list is exactly how a fix ends up shipped without a patch.

const fs = require("node:fs");
const path = require("node:path");
const { execFileSync } = require("node:child_process");

const scriptDirectory = __dirname;
const defaultRepository = path.resolve(scriptDirectory, "..");

function parseArgs(argv) {
  const options = {
    repository: defaultRepository,
    artifactRoot: process.env.CG_HOTFIX_ARTIFACT_ROOT || defaultRepository,
    artifactDir: "release/2.2-103-hotfixes",
    outEn: path.join(defaultRepository, "docs/hotfix-patches.md"),
    outZh: path.join(defaultRepository, "docs/zh-CN/hotfix-patches.md")
  };
  for (let index = 0; index < argv.length; index += 1) {
    const argument = argv[index];
    const value = argv[index + 1];
    switch (argument) {
      case "--repo": options.repository = path.resolve(value); index += 1; break;
      case "--artifact-root": options.artifactRoot = path.resolve(value); index += 1; break;
      case "--artifact-dir": options.artifactDir = value; index += 1; break;
      case "--out-en": options.outEn = path.resolve(value); index += 1; break;
      case "--out-zh": options.outZh = path.resolve(value); index += 1; break;
      case "-h":
      case "--help":
        console.log("usage: render-hotfix-catalog.cjs [--repo DIR] [--artifact-root DIR] [--artifact-dir REL] [--out-en FILE] [--out-zh FILE]");
        process.exit(0);
        break;
      default:
        throw new Error(`unknown argument: ${argument}`);
    }
  }
  return options;
}

function readManifest(archive) {
  const json = execFileSync(
    "tar",
    ["-xzOf", archive, "clusterguard-hotfix/HOTFIX-MANIFEST.json"],
    { encoding: "utf8", maxBuffer: 32 * 1024 * 1024 }
  );
  const manifest = JSON.parse(json);
  if (manifest.kind !== "hotfix") {
    throw new Error(`${archive} is not a hotfix patch`);
  }
  manifest.archive = path.basename(archive);
  manifest.archiveSha256 = execFileSync("shasum", ["-a", "256", archive], { encoding: "utf8" }).split(/\s+/)[0];
  return manifest;
}

function collect(options) {
  const directory = path.join(options.artifactRoot, options.artifactDir);
  if (!fs.existsSync(directory)) {
    throw new Error(`hotfix artifact directory not found: ${directory}`);
  }
  const archives = fs
    .readdirSync(directory)
    .filter((name) => name.endsWith(".cgpatch"))
    .sort();
  if (archives.length === 0) {
    throw new Error(`no hotfix patches found in ${directory}`);
  }
  return archives.map((name) => readManifest(path.join(directory, name)));
}

function restartUnits(manifest) {
  const units = [];
  for (const entry of manifest.files) {
    if (entry.restart_unit && !units.includes(entry.restart_unit)) units.push(entry.restart_unit);
  }
  return units;
}

function renderEnglish(manifests, artifactDir) {
  const lines = [];
  lines.push("# Hotfix patch catalogue");
  lines.push("");
  lines.push("> Generated by `scripts/render-hotfix-catalog.cjs` from the signed patches that");
  lines.push("> exist on disk. Do not edit by hand — rebuild the patch and re-render instead.");
  lines.push("> `tools/verify-hotfix-patch-catalog.cjs` fails when a fix commit has no patch or");
  lines.push("> when this file disagrees with the artifacts.");
  lines.push("");
  lines.push("A `.cgupgrade` carries whole RPMs and can only be applied by the rolling upgrade");
  lines.push("executor. A hotfix patch carries exactly what one bug fix changed: the rebuilt");
  lines.push("binaries, the systemd units it touched, the source diff as evidence, and an");
  lines.push("apply/rollback pair. Every bug fix against a released version must leave one behind,");
  lines.push("otherwise a running site can only pick the fix up by waiting for the next release.");
  lines.push("");
  lines.push("| Hotfix | Severity | Fix commit | Artifact |");
  lines.push("| --- | --- | --- | --- |");
  for (const manifest of manifests) {
    lines.push(`| [${manifest.hotfix_id}](#${manifest.hotfix_id.toLowerCase().replace(/-/g, "-")}) | ${manifest.severity} | \`${manifest.fix_commit.slice(0, 7)}\` | \`${manifest.archive}\` |`);
  }
  lines.push("");
  lines.push("## Applying a patch");
  lines.push("");
  lines.push("```bash");
  lines.push(`tar -xzf ${artifactDir}/<artifact>.cgpatch`);
  lines.push("cd clusterguard-hotfix");
  lines.push("bash apply.sh            # backs up, verifies SHA-256, installs, daemon-reload");
  lines.push("systemctl restart <unit> # apply.sh prints the units it needs; it never restarts by itself");
  lines.push("bash rollback.sh         # restores from the newest backup manifest");
  lines.push("```");
  lines.push("");
  for (const manifest of manifests) {
    lines.push(`## ${manifest.hotfix_id} — ${manifest.title.en}`);
    lines.push("");
    lines.push(`- Severity: ${manifest.severity}`);
    lines.push(`- Fix commit: \`${manifest.fix_commit}\` (baseline \`${manifest.base_commit}\`)`);
    lines.push(`- Applies to: ${manifest.source.version}-${manifest.source.release} → ${manifest.target.version}-${manifest.target.release} (${manifest.target.rpm_architecture})`);
    lines.push(`- Artifact: \`${artifactDir}/${manifest.archive}\``);
    lines.push(`- SHA-256: \`${manifest.archiveSha256}\``);
    lines.push(`- Source diff: \`${manifest.source_patch}\``);
    lines.push("- Payload:");
    for (const entry of manifest.files) {
      const target = entry.install_path || "installer-only, no site path";
      lines.push(`  - \`${entry.artifact}\` → \`${target}\` (${entry.mode})`);
    }
    const units = restartUnits(manifest);
    lines.push(`- Restart required: ${units.length ? units.map((unit) => `\`${unit}\``).join(", ") : "none"}`);
    lines.push("");
    lines.push("### Symptom");
    lines.push("");
    lines.push(manifest.symptom.en);
    lines.push("");
    lines.push("### Root cause");
    lines.push("");
    lines.push(manifest.root_cause.en);
    lines.push("");
    lines.push("### Fix");
    lines.push("");
    lines.push(manifest.fix.en);
    lines.push("");
    if ((manifest.applies_to || []).length > 0) {
      lines.push("### When to apply");
      lines.push("");
      for (const item of manifest.applies_to) lines.push(`- ${item}`);
      lines.push("");
    }
    lines.push("### Verification");
    lines.push("");
    for (const step of manifest.verification || []) lines.push(`- \`${step}\``);
    lines.push("");
    lines.push("### Rollback");
    lines.push("");
    lines.push(typeof manifest.rollback === "string" ? manifest.rollback : manifest.rollback.en);
    lines.push("");
  }
  return lines.join("\n") + "\n";
}

function renderChinese(manifests, artifactDir) {
  const lines = [];
  lines.push("# 热修补丁台账");
  lines.push("");
  lines.push("> 本文件由 `scripts/render-hotfix-catalog.cjs` 依据磁盘上真实存在的签名补丁包生成，");
  lines.push("> 请勿手工编辑：重新构建补丁包后重新生成本文件。");
  lines.push("> `tools/verify-hotfix-patch-catalog.cjs` 会在“修复提交没有补丁包”或“本文件与产物不一致”时失败。");
  lines.push("");
  lines.push("`.cgupgrade` 携带完整 RPM，只能由滚动升级执行器应用；热修补丁包只携带一次 bug 修复");
  lines.push("真正改动的东西：重新构建的二进制、被修改的 systemd 单元、作为证据的源码差异，以及一对");
  lines.push("apply/rollback 脚本。针对已发布版本的每一个 bug 修复都必须留下一个补丁包，否则现场只能");
  lines.push("等下一个完整版本才能拿到修复。");
  lines.push("");
  lines.push("| 补丁编号 | 严重级别 | 修复提交 | 产物 |");
  lines.push("| --- | --- | --- | --- |");
  for (const manifest of manifests) {
    lines.push(`| ${manifest.hotfix_id} | ${manifest.severity} | \`${manifest.fix_commit.slice(0, 7)}\` | \`${manifest.archive}\` |`);
  }
  lines.push("");
  lines.push("## 应用补丁");
  lines.push("");
  lines.push("```bash");
  lines.push(`tar -xzf ${artifactDir}/<产物文件名>.cgpatch`);
  lines.push("cd clusterguard-hotfix");
  lines.push("bash apply.sh            # 备份、校验 SHA-256、安装、daemon-reload");
  lines.push("systemctl restart <单元> # apply.sh 只打印需要重启的单元，不自动重启");
  lines.push("bash rollback.sh         # 按最新备份清单回滚");
  lines.push("```");
  lines.push("");
  for (const manifest of manifests) {
    lines.push(`## ${manifest.hotfix_id} — ${manifest.title.zh}`);
    lines.push("");
    lines.push(`- 严重级别：${manifest.severity}`);
    lines.push(`- 修复提交：\`${manifest.fix_commit}\`（基线 \`${manifest.base_commit}\`）`);
    lines.push(`- 适用版本：${manifest.source.version}-${manifest.source.release} → ${manifest.target.version}-${manifest.target.release}（${manifest.target.rpm_architecture}）`);
    lines.push(`- 产物：\`${artifactDir}/${manifest.archive}\``);
    lines.push(`- SHA-256：\`${manifest.archiveSha256}\``);
    lines.push(`- 源码差异：\`${manifest.source_patch}\``);
    lines.push("- 交付内容：");
    for (const entry of manifest.files) {
      const target = entry.install_path || "仅安装器，现场无对应路径";
      lines.push(`  - \`${entry.artifact}\` → \`${target}\`（${entry.mode}）`);
    }
    const units = restartUnits(manifest);
    lines.push(`- 需要重启：${units.length ? units.map((unit) => `\`${unit}\``).join("、") : "无"}`);
    lines.push("");
    lines.push("### 现象");
    lines.push("");
    lines.push(manifest.symptom.zh);
    lines.push("");
    lines.push("### 根因");
    lines.push("");
    lines.push(manifest.root_cause.zh);
    lines.push("");
    lines.push("### 修复");
    lines.push("");
    lines.push(manifest.fix.zh);
    lines.push("");
    if ((manifest.applies_to || []).length > 0) {
      lines.push("### 何时需要应用");
      lines.push("");
      for (const item of manifest.applies_to) lines.push(`- ${item}`);
      lines.push("");
    }
    lines.push("### 验证");
    lines.push("");
    for (const step of manifest.verification || []) lines.push(`- \`${step}\``);
    lines.push("");
    lines.push("### 回滚");
    lines.push("");
    lines.push(typeof manifest.rollback === "string" ? manifest.rollback : manifest.rollback.zh);
    lines.push("");
  }
  return lines.join("\n") + "\n";
}

const main = () => {
  const options = parseArgs(process.argv.slice(2));
  const manifests = collect(options).sort((left, right) => right.hotfix_id.localeCompare(left.hotfix_id));
  fs.mkdirSync(path.dirname(options.outEn), { recursive: true });
  fs.mkdirSync(path.dirname(options.outZh), { recursive: true });
  fs.writeFileSync(options.outEn, renderEnglish(manifests, options.artifactDir));
  fs.writeFileSync(options.outZh, renderChinese(manifests, options.artifactDir));
  console.log(`rendered ${manifests.length} hotfix patches`);
  console.log(`en=${options.outEn}`);
  console.log(`zh=${options.outZh}`);
};

main();
